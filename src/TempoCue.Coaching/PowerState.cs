namespace TempoCue.Coaching;

/// <summary>
/// Общая оценка силы игрока в текущем состоянии матчапа.
/// Фиксированный список не позволяет правилам использовать случайные значения.
/// </summary>
public enum PowerState
{
    /// <summary>Прямое сражение сейчас особенно рискованно.</summary>
    Dangerous,

    /// <summary>Играть можно только с повышенной осторожностью.</summary>
    Cautious,

    /// <summary>Матчап допускает активную игру при правильных условиях.</summary>
    Playable,

    /// <summary>Текущее состояние даёт игроку заметное преимущество.</summary>
    Favorable
}
