using OpenCvSharp;

namespace TempoCue.Vision;

/// <summary>
/// Отключает собственное распараллеливание OpenCV. По умолчанию оно берёт столько
/// потоков, сколько в машине логических процессоров, и делает это внутри каждого
/// вызова — поверх наших. Из-за этого распознавание занимало больше процессора,
/// чем разрешала настройка: она задавала лишь внешний множитель.
///
/// Замер показал, что внутреннее распараллеливание не просто лишнее, а вредное:
/// операции сравнения крошечные (окно 33 x 33 против шаблона в 8–14 пикселей), и
/// синхронизация обходится дороже самой работы. С одним внутренним потоком кадр
/// считается на десятую часть быстрее при вчетверо меньшем числе занятых ядер.
/// </summary>
internal static class OpenCvParallelism
{
    private static readonly object Sync = new();
    private static bool _isConfigured;

    /// <summary>
    /// Настройка глобальна для процесса, поэтому применяется один раз. Все вызовы
    /// OpenCV в TempoCue идут по одному кадру и уже разложены по нашим потокам.
    /// </summary>
    public static void EnsureSingleThreaded()
    {
        if (_isConfigured)
        {
            return;
        }

        lock (Sync)
        {
            if (_isConfigured)
            {
                return;
            }

            Cv2.SetNumThreads(1);
            _isConfigured = true;
        }
    }
}
