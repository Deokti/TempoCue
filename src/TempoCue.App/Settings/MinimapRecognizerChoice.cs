/// <summary>
/// Каким распознавателем разбирать миникарту. Выбор применяется при следующем
/// запуске: распознаватель создаётся один раз вместе с сессией захвата.
/// </summary>
/// <remarks>
/// Раньше выбор был галочкой «экспериментальное распознавание», потому что
/// вариантов было два. Со своей моделью их стало три, и булево значение перестало
/// их выражать: галочка не отвечает на вопрос «какой именно из двух».
/// </remarks>
public enum MinimapRecognizerChoice
{
    /// <summary>Штатный конвейер: цветные контуры и сравнение портретов.</summary>
    Default = 0,

    /// <summary>Своя модель: детектор центров плюс опознание по вырезам.</summary>
    OwnModel = 1,

    /// <summary>Сторонняя модель DeeperLeague.</summary>
    DeeperLeague = 2
}
